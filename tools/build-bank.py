#!/usr/bin/env python3
"""Convert kodshim-practice.csv into src/data/bank.js.

The CSV is the single source of truth for the question bank. Run this after
editing it:

    python3 tools/build-bank.py

Each row becomes a "card" the game can turn into several question types.
"""
import csv
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
CSV = ROOT / "kodshim-practice.csv"
OUT = ROOT / "src" / "data" / "bank.js"

# Level metadata the game shows on the map. Names are lightly edited from the
# CSV's level-name column so they read as chapter titles.
LEVELS = {
    "1": {"slug": "animals",    "title": "Which Animals, and When",
          "hebrew": "מֵאֵיזֶה מִין", "tagline": "The five species, their names, their ages."},
    "2": {"slug": "categories", "title": "Kinds of Korbanot",
          "hebrew": "סוּגֵי הַקָּרְבָּנוֹת", "tagline": "Olah, chatat, asham, shelamim. Most-holy and lighter-holy."},
    "3": {"slug": "bringers",   "title": "Who Brings What",
          "hebrew": "מִי מֵבִיא מָה", "tagline": "Nazir, metzora, yoledet, nasi, and the asham family."},
    "4": {"slug": "avodah",     "title": "At the Altar",
          "hebrew": "עֲבוֹדַת הַמִּזְבֵּחַ", "tagline": "Blood, fire, eating times, and what goes wrong."},
    "5": {"slug": "tzibur",     "title": "The Nation's Offerings",
          "hebrew": "קָרְבְּנוֹת צִבּוּר", "tagline": "Tamid, musaf, the breads, Pesach, bechor and ma'aser."},
}

VOCAB_RE = re.compile(r"^(?P<translit>[^—]+?)\s*—\s*(?P<hebrew>[^(]+?)(?:\s*\((?P<note>.*)\))?\s*$")

# Illustrations already in the repo for the Level 1 vocabulary.
VOCAB_IMAGES = {
    "L1-01": "calf.png", "L1-02": "cow-f.png", "L1-03": "cow-male.png", "L1-04": "cow-f.png",
    "L1-05": "lamb.png", "L1-06": "ewe.png", "L1-07": "ram.png", "L1-08": "ewe.png",
    "L1-09": "kid-goat.png", "L1-10": "kid-goat.png", "L1-11": "male-goat.png", "L1-12": "male-goat.png",
}


def split_hebrew_answer(s):
    """'תּוֹר / תּוֹרִים' -> ['תּוֹר', 'תּוֹרִים']"""
    return [p.strip() for p in s.split("/") if p.strip()]


def main():
    rows = list(csv.DictReader(CSV.open(encoding="utf-8")))
    cards = []
    for r in rows:
        cid = r["question-id"].strip()
        lvl = r["level"].strip()
        q = r["question-english"].strip()
        a = r["answer-english"].strip()
        card = {
            "id": cid,
            "level": int(lvl),
            "q": q,
            "a": a,
            "qHe": r["question-hebrew"].strip(),
            "aHe": r["answer-hebrew"].strip(),
            "src": {
                "torah": r["biblical-source"].strip(),
                "rambam": r["mishnah-torah-source"].strip(),
            },
        }
        if lvl == "1" and "?" not in q:
            # Vocabulary row: "A young male cow (calf)" -> "egel — עֵגֶל"
            m = VOCAB_RE.match(a)
            card["kind"] = "vocab"
            card["translit"] = m.group("translit").strip() if m else a
            card["hebrewWord"] = split_hebrew_answer(r["answer-hebrew"])[0]
            card["hebrewForms"] = split_hebrew_answer(r["answer-hebrew"])
            card["note"] = (m.group("note") or "").strip() if m else ""
            card["english"] = q
            if cid in VOCAB_IMAGES:
                card["image"] = VOCAB_IMAGES[cid]
            # Species group for sorting games.
            ql = q.lower()
            card["group"] = ("cow" if "cow" in ql else "sheep" if "sheep" in ql
                             else "goat" if "goat" in ql else "bird")
        else:
            card["kind"] = "fact"
        cards.append(card)

    levels = []
    for num, meta in LEVELS.items():
        n = sum(1 for c in cards if c["level"] == int(num))
        levels.append({"num": int(num), "cards": n, **meta})

    payload = {"levels": levels, "cards": cards}
    js = ("// GENERATED by tools/build-bank.py from kodshim-practice.csv. Do not edit by hand.\n"
          "window.KODSHIM_BANK = " + json.dumps(payload, ensure_ascii=False, indent=1) + ";\n")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(js, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(cards)} cards, {len(levels)} levels")


if __name__ == "__main__":
    main()
